__device__ unsigned int crc_shift(unsigned int crc, unsigned long long bytes) {
  unsigned int power = 0;
  while (bytes) {
    if (bytes & 1) {
      unsigned int shifted = 0;
      for (unsigned int bit = 0; bit < 32; ++bit)
        if (crc & (1u << bit))
          shifted ^= crc_shift_matrix[power][bit];
      crc = shifted;
    }
    ++power;
    bytes >>= 1;
  }
  return crc;
}

__device__ unsigned long long part_length(unsigned long long n, unsigned int parts,
                                         unsigned int index) {
  return n / parts + (index < n % parts);
}
__device__ unsigned long long part_offset(unsigned long long n, unsigned int parts,
                                         unsigned int index) {
  return (n / parts) * index + min((unsigned long long)index, n % parts);
}
__device__ void crc_reduce(unsigned int *crc, unsigned long long *length) {
  unsigned int t = threadIdx.x;
  __syncthreads();
  for (unsigned int stride = 1; stride < 256; stride *= 2) {
    if ((t % (stride * 2)) == 0) {
      crc[t] = crc_shift(crc[t], length[t + stride]) ^ crc[t + stride];
      length[t] += length[t + stride];
    }
    __syncthreads();
  }
}
extern "C" __global__ void crc32_parts(const Segment *batch,
