  if (blockIdx.x >= d.crc_tiles) return;
  unsigned int t = threadIdx.x;
  unsigned long long n = encode ? sizes[blockIdx.y] : d.stored;
  if (n == 0 || n > d.capacity || (encode && status[blockIdx.y] != 0)) {
    if (t == 0) partials[d.crc_offset + blockIdx.x] = 0;
    return;
  }
  __shared__ unsigned int table[256], crc[256];
  __shared__ unsigned long long length[256];
  table[t] = crc_byte_table[t];
  __syncthreads();
  unsigned long long tile_size = part_length(n, d.crc_tiles, blockIdx.x);
  unsigned long long start = part_offset(n, d.crc_tiles, blockIdx.x)
                          + part_offset(tile_size, 256, t);
  length[t] = part_length(tile_size, 256, t);
  const unsigned char *src = (const unsigned char *)(encode ? d.target : d.source);
  unsigned int value = 0xffffffffu;
  for (unsigned long long i = 0; i < length[t]; ++i)
    value = table[(value ^ src[start + i]) & 255] ^ (value >> 8);
  crc[t] = value ^ 0xffffffffu;
  crc_reduce(crc, length);
  if (t == 0) partials[d.crc_offset + blockIdx.x] = crc[0];
}
extern "C" __global__ void crc32_finish(const Segment *batch,
                                         const unsigned long long *sizes,
                                         const unsigned int *partials,
                                         unsigned int *checksums, int encode) {
  const Segment d = batch[blockIdx.x];
  unsigned long long n = encode ? sizes[blockIdx.x] : d.stored;
  unsigned int t = threadIdx.x;
  __shared__ unsigned int crc[256];
  __shared__ unsigned long long length[256];
  crc[t] = t < d.crc_tiles ? partials[d.crc_offset + t] : 0;
  length[t] = t < d.crc_tiles ? part_length(n, d.crc_tiles, t) : 0;
  crc_reduce(crc, length);
  if (t == 0) checksums[blockIdx.x] = crc[0];
}
